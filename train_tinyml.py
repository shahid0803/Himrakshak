#!/usr/bin/env python3
"""Train and export the HimRakshak synthetic TinyML demonstration tree.

Run: python -m pip install -r requirements-tinyml.txt
     python train_tinyml.py

The generated data is synthetic and must not be represented as field data.
"""
from __future__ import annotations

import argparse
import json
import hashlib
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, recall_score
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier, _tree

from scripts.generate_tinyml_dataset import FEATURES, generate

ROOT = Path(__file__).resolve().parent
DATASET = ROOT / "data" / "processed" / "himrakshak_synthetic_v2.csv"
MODEL_DIR = ROOT / "models"
MODEL_JSON = MODEL_DIR / "himrakshak_tinyml_v2.json"
MODEL_HEADER = ROOT / "wokwi_esp32_demo" / "HimRakshakModel.h"
METRICS_JSON = MODEL_DIR / "training_metrics_v2.json"


def export_tree(model: DecisionTreeClassifier) -> dict:
    tree = model.tree_
    feature, threshold, left, right, classes = [], [], [], [], []
    for index in range(tree.node_count):
        feature_index = int(tree.feature[index])
        feature.append(feature_index)
        threshold.append(float(tree.threshold[index]) if feature_index >= 0 else 0.0)
        left.append(int(tree.children_left[index]))
        right.append(int(tree.children_right[index]))
        classes.append(int(np.argmax(tree.value[index][0])))
    return {
        "feature": feature,
        "threshold": [round(value, 8) for value in threshold],
        "children_left": left,
        "children_right": right,
        "class": classes,
    }


def render_header(tree_data: dict, model_sha: str) -> str:
    tree = tree_data
    count = len(tree["feature"])
    def arr(name: str, values: list, suffix: str = "") -> str:
        return f"static const {suffix or 'int16_t'} {name}[{count}] = {{\n  " + ", ".join(str(x) for x in values) + "\n};"
    lines = [
        "// Generated by train_tinyml.py. Do not hand-edit.",
        "// Synthetic demonstration model; not field-validated.",
        "#pragma once", "#include <stdint.h>", "namespace HimRakshakTinyML {",
        f'static const char MODEL_ID[] = "himrakshak-synthetic-demo-tree-v2";',
        f'static const char MODEL_SHA256[] = "{model_sha}";',
        f"static const int NODE_COUNT = {count};",
        arr("FEATURE", tree["feature"]),
        arr("LEFT_CHILD", tree["children_left"]),
        arr("RIGHT_CHILD", tree["children_right"]),
        arr("PREDICTED_CLASS", tree["class"]),
        arr("THRESHOLD", tree["threshold"], "float"),
        "inline int predict(const float *x) {",
        "  int node = 0; int steps = 0;",
        "  while (FEATURE[node] >= 0 && steps++ < NODE_COUNT) {",
        "    node = (x[FEATURE[node]] <= THRESHOLD[node]) ? LEFT_CHILD[node] : RIGHT_CHILD[node];",
        "  }",
        "  if (node < 0 || node >= NODE_COUNT || steps > NODE_COUNT) return -1;",
        "  int result = PREDICTED_CLASS[node];",
        "  return (result >= 0 && result <= 2) ? result : -1;",
        "}",
        "}  // namespace HimRakshakTinyML",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--generate", action="store_true", help="regenerate synthetic dataset")
    parser.add_argument("--count", type=int, default=240000)
    parser.add_argument("--seed", type=int, default=20261117)
    args = parser.parse_args()

    if args.generate or not DATASET.exists():
        counts = generate(DATASET, count=args.count, seed=args.seed)
        print("Synthetic data generated:", counts)

    df = pd.read_csv(DATASET)
    missing = sorted(set(FEATURES + ["risk_class"]) - set(df.columns))
    if missing:
        raise SystemExit(f"Dataset is missing columns: {missing}")
    if df[FEATURES + ["risk_class"]].isna().any().any():
        raise SystemExit("Dataset contains missing feature/target values")
    X = df.loc[:, FEATURES].astype(float)
    y = df["risk_class"].astype(int)
    if set(y.unique()) != {0, 1, 2}:
        raise SystemExit("Dataset must contain classes 0, 1 and 2")

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.25, random_state=42, stratify=y
    )
    candidates = []
    for depth in (4, 5, 6):
        candidate = DecisionTreeClassifier(
            max_depth=depth, min_samples_leaf=8, class_weight="balanced", random_state=42
        )
        candidate.fit(X_train, y_train)
        pred = candidate.predict(X_test)
        metrics = {
            "accuracy": float(accuracy_score(y_test, pred)),
            "critical_recall": float(recall_score(y_test, pred, labels=[0, 1, 2], average=None, zero_division=0)[2]),
            "nodes": int(candidate.tree_.node_count),
            "depth": int(candidate.get_depth()),
        }
        candidates.append((candidate, metrics))
    # Prioritize critical recall, then balanced overall accuracy, then compactness.
    model, selected = max(candidates, key=lambda item: (item[1]["critical_recall"], item[1]["accuracy"], -item[1]["nodes"]))
    predictions = model.predict(X_test)
    tree_data = export_tree(model)
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    MODEL_JSON.parent.mkdir(parents=True, exist_ok=True)
    metadata = {
        "model_id": "himrakshak-synthetic-demo-tree-v2",
        "model_version": "2.0.0-demo-synthetic",
        "dataset_revision": "240k-synthetic-reproducible-seed-20261117",
        "model_type": "DecisionTreeClassifier",
        "training_source": "synthetic_demonstration_scenarios_only",
        "dataset_generation_method": "balanced_class_conditioned_monte_carlo_with_threshold_rule_rejection_and_measurement_noise",
        "dataset_generation_seed": int(args.seed) if args.generate else None,
        "field_validated": False,
        "features": list(FEATURES),
        "feature_names": list(FEATURES),
        "class_names": {"0": "NORMAL", "1": "WARNING", "2": "CRITICAL"},
        "dataset_rows": int(len(df)),
        "class_counts": {str(int(k)): int(v) for k, v in y.value_counts().sort_index().items()},
        "train_rows": int(len(X_train)),
        "test_rows": int(len(X_test)),
        "selected_metrics": selected,
        "classification_report": classification_report(y_test, predictions, labels=[0, 1, 2], target_names=["NORMAL", "WARNING", "CRITICAL"], output_dict=True, zero_division=0),
        "confusion_matrix": confusion_matrix(y_test, predictions, labels=[0, 1, 2]).tolist(),
        "candidate_models": [metrics for _, metrics in candidates],
        "sklearn_version": sklearn.__version__,
        "trained_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "limitations": [
            "Class labels are assigned by explicit illustrative threshold rules after balanced class-conditioned rejection sampling; they are not observed landslide outcomes.",
            "Increasing the synthetic row count increases sampled combinations, not the amount of real-world evidence.",
            "Metrics measure agreement with synthetic labels, not real landslide prediction accuracy.",
            "Soil temperature, groundwater and some motion/vibration fields are virtual or derived demonstration proxies in Wokwi.",
        ],
        "tree": tree_data,
    }
    serialized = json.dumps(metadata, indent=2, sort_keys=True)
    model_hash = hashlib.sha256(serialized.encode("utf-8")).hexdigest()
    metadata["model_sha256"] = model_hash
    MODEL_JSON.write_text(json.dumps(metadata, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    MODEL_HEADER.write_text(render_header(tree_data, model_hash), encoding="utf-8")
    metrics_only = {key: metadata[key] for key in (
        "model_id", "model_version", "dataset_revision", "dataset_generation_method",
        "dataset_generation_seed", "model_type", "training_source", "field_validated",
        "features", "dataset_rows", "class_counts", "train_rows", "test_rows",
        "selected_metrics", "classification_report", "confusion_matrix",
        "candidate_models", "sklearn_version", "trained_at", "limitations", "model_sha256"
    )}
    METRICS_JSON.write_text(json.dumps(metrics_only, indent=2) + "\n", encoding="utf-8")
    print("Selected model:", selected)
    print("Classification report:\n", classification_report(y_test, predictions, labels=[0, 1, 2], target_names=["NORMAL", "WARNING", "CRITICAL"], zero_division=0))
    print("Confusion matrix:\n", confusion_matrix(y_test, predictions, labels=[0, 1, 2]))
    print("Exported:", MODEL_JSON)
    print("Exported:", MODEL_HEADER)

if __name__ == "__main__":
    main()
